constexpr byte SEA_CHUNK = 0xFF;

// The chunks that have each of the dungeons, and each of the shrines
static const byte DUNGEON_CHUNKS[8] = { 0x4F, 0x45, 0xA4, 0x17, 0x19, 0x63, 0xFE, 0x88 };
static const byte SHRINE_CHUNKS[8] = { 0x4E, 0x58, 0xE2, 0x04, 0x2C, 0xC5, 0x00, 0xDE };

bool WorldMap::load(bool underworld, const Savegame &savegame) {
	_loaded = false;

	Common::File f;
	if (!f.open(underworld ? "under.dat" : "brit.dat"))
		return false;

	for (int chunk = 0; chunk < CHUNK_COUNT; ++chunk) {
		byte data[CHUNK_SIZE * CHUNK_SIZE];
		int fileChunk = underworld ? chunk : BRITANNIA_CHUNKS[chunk];

		if (fileChunk == SEA_CHUNK) {
			memset(data, TILE_WATER, sizeof(data));
		} else if (!f.seek(fileChunk * sizeof(data)) || f.read(data, sizeof(data)) != sizeof(data)) {
			return false;
		}

		const int baseX = (chunk % (WORLD_SIZE / CHUNK_SIZE)) * CHUNK_SIZE;
		const int baseY = (chunk / (WORLD_SIZE / CHUNK_SIZE)) * CHUNK_SIZE;
		for (int y = 0; y < CHUNK_SIZE; ++y)
			memcpy(&_tiles[(baseY + y) * WORLD_SIZE + baseX], &data[y * CHUNK_SIZE], CHUNK_SIZE);
	}

	_loaded = true;
	_underworld = underworld;
	applyQuestState(savegame);
	return true;
}

void WorldMap::applyQuestState(const Savegame &sg) {
	for (int chunk = 0; chunk < CHUNK_COUNT; ++chunk) {
		const int baseX = (chunk % (WORLD_SIZE / CHUNK_SIZE)) * CHUNK_SIZE;
		const int baseY = (chunk / (WORLD_SIZE / CHUNK_SIZE)) * CHUNK_SIZE;

		// Dungeon entrances are blocked by a boulder until the quest that opens them is done
		bool sealDungeons = true;
		for (int i = 0; i < 8; ++i) {
			if (DUNGEON_CHUNKS[i] == chunk) {
				sealDungeons = sg._unk032A[i] == 0;
				break;
			}
		}

		// Shrines are in ruins once they've been destroyed
		bool ruinShrines = false;
		for (int i = 0; i < 8; ++i) {
			if (SHRINE_CHUNKS[i] == chunk) {
				ruinShrines = sg._unk0332[i] > 0x7F;
				break;
			}
		}

		for (int y = 0; y < CHUNK_SIZE; ++y) {
			for (int x = 0; x < CHUNK_SIZE; ++x) {
				byte &tile = _tiles[(baseY + y) * WORLD_SIZE + baseX + x];

				if (tile >= TILE_CAVE && tile <= TILE_DUNGEON && sealDungeons)
					tile = TILE_SEALED_DUNGEON;
				else if (tile == TILE_SHRINE && ruinShrines)
					tile = TILE_RUINS;
			}
		}
	}
}

